import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import { Type } from 'class-transformer';
import {
  ArrayMinSize,
  IsArray,
  IsDateString,
  IsEmail,
  IsEnum,
  IsIn,
  IsInt,
  IsNotEmpty,
  IsOptional,
  IsString,
  Min,
  ValidateNested,
} from 'class-validator';
import type { QuantitySource } from '../../../../core/prisma/client';

const INSTALMENT_PLAN_TYPES = ['LAYBY', 'INSTALMENT'] as const;

// pos-hardware/31 §2 — kept as a local literal tuple (the same
// `IsEnum(ARRAY)` + `import type` convention `fragment.dto.ts` already
// uses), not a class-validator dependency on the Prisma-generated enum
// object itself.
const QUANTITY_SOURCES = ['TYPED', 'SCALE_WEIGHT', 'BOM_RECIPE_SCALE'] as const satisfies readonly QuantitySource[];

export class InstalmentScheduleLineDto {
  @ApiProperty()
  @IsDateString()
  dueDate!: string;

  @ApiProperty()
  @IsInt()
  @Min(1)
  amountMinor!: number;
}

/**
 * finance-accounting/151-layby-installment-sales.md — requested at the
 * point of sale, alongside the ordinary line list. Omit entirely for an
 * ordinary immediate-tender-in-full sale, today's exact behaviour.
 */
export class PosInstalmentPlanDto {
  @ApiProperty({ enum: INSTALMENT_PLAN_TYPES })
  @IsIn(INSTALMENT_PLAN_TYPES)
  type!: (typeof INSTALMENT_PLAN_TYPES)[number];

  @ApiProperty()
  @IsInt()
  @Min(0)
  depositMinor!: number;

  @ApiProperty({ type: [InstalmentScheduleLineDto] })
  @IsArray()
  @ArrayMinSize(1)
  @ValidateNested({ each: true })
  @Type(() => InstalmentScheduleLineDto)
  schedule!: InstalmentScheduleLineDto[];
}

/** pos-hardware/31 §2 — a modifier's price delta, folded into the order
 *  item's own `unitPrice` server-side; `key`/`label` are display-only,
 *  written to `PosLineModifier` after the sale commits. */
export class PosLineModifierDto {
  @ApiProperty()
  @IsString()
  @IsNotEmpty()
  key!: string;

  @ApiProperty()
  @IsString()
  @IsNotEmpty()
  label!: string;

  @ApiProperty()
  @IsInt()
  priceDeltaMinor!: number;
}

/** pos-hardware/31 §2 — where this line's quantity came from, when it is
 *  not a typed integer. */
export class PosLineQuantitySourceDto {
  @ApiProperty({ enum: QUANTITY_SOURCES })
  @IsEnum(QUANTITY_SOURCES)
  source!: QuantitySource;

  @ApiPropertyOptional({ description: 'Set only when source = BOM_RECIPE_SCALE.' })
  @IsOptional()
  @IsString()
  recipeId?: string;
}

export class PosSaleLineDto {
  @ApiProperty()
  @IsString()
  @IsNotEmpty()
  variantId!: string;

  @ApiProperty()
  @IsInt()
  @Min(1)
  quantity!: number;

  /** pos-hardware/31 §2 — present only when this line carries modifiers or
   *  a non-typed quantity source; generated by the till UI (not by this
   *  DTO), a stable identity distinct from `variantId` so two same-variant
   *  lines with different modifiers are never confused for one another. */
  @ApiPropertyOptional()
  @IsOptional()
  @IsString()
  lineRef?: string;

  @ApiPropertyOptional({ type: [PosLineModifierDto] })
  @IsOptional()
  @IsArray()
  @ValidateNested({ each: true })
  @Type(() => PosLineModifierDto)
  modifiers?: PosLineModifierDto[];

  @ApiPropertyOptional({ type: PosLineQuantitySourceDto })
  @IsOptional()
  @ValidateNested()
  @Type(() => PosLineQuantitySourceDto)
  quantitySource?: PosLineQuantitySourceDto;
}

export class CreatePosSaleDto {
  @ApiProperty({ type: [PosSaleLineDto] })
  @IsArray()
  @ArrayMinSize(1)
  @ValidateNested({ each: true })
  @Type(() => PosSaleLineDto)
  lines!: PosSaleLineDto[];

  @ApiPropertyOptional({ description: 'Only when the cashier takes the details — a till sale is anonymous by default.' })
  @IsOptional()
  @IsString()
  customerName?: string;

  @ApiPropertyOptional()
  @IsOptional()
  @IsString()
  customerPhone?: string;

  @ApiPropertyOptional()
  @IsOptional()
  @IsEmail()
  customerEmail?: string;

  @ApiPropertyOptional({ type: PosInstalmentPlanDto })
  @IsOptional()
  @ValidateNested()
  @Type(() => PosInstalmentPlanDto)
  instalmentPlan?: PosInstalmentPlanDto;
}
